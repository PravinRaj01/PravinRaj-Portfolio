# app/models/rag.py -- RAG_MIGRATION_PLAN.md §6. One row per retrievable
# "chunk" of the portfolio (a project, a job, a skill group...), embedded for
# vector search and indexed for full-text search.
from pgvector.sqlalchemy import Vector
from sqlalchemy import Computed, Index, Integer, String, Text
from sqlalchemy.dialects.postgresql import TSVECTOR
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, TimestampsRequired, UUIDPk

EMBEDDING_DIMS = 768

# Immutable (explicit 'english' config), so Postgres accepts it as a stored
# generated column. Title weighted A, content B, so a title hit outranks a
# passing mention.
SEARCH_TSV_EXPR = (
    "setweight(to_tsvector('english', coalesce(title, '')), 'A') || "
    "setweight(to_tsvector('english', coalesce(content, '')), 'B')"
)


class PortfolioChunk(UUIDPk, TimestampsRequired, Base):
    __tablename__ = "portfolio_chunks"

    # 'project:<uuid>', 'skills:professional:<category>' -- a stable identity so
    # re-indexing upserts instead of duplicating.
    source_key: Mapped[str] = mapped_column(Text, nullable=False, unique=True)
    source_type: Mapped[str] = mapped_column(String(32), nullable=False)
    mode: Mapped[str] = mapped_column(String(20), nullable=False)  # professional | creative | both
    title: Mapped[str] = mapped_column(Text, nullable=False)
    content: Mapped[str] = mapped_column(Text, nullable=False)
    # sha256 of mode + title + content (see rag_index.Chunk.digest): lets
    # re-indexing skip unchanged rows, which is what keeps it inside the free
    # tier's 1K embedding requests/day.
    content_hash: Mapped[str] = mapped_column(String(64), nullable=False)
    token_estimate: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")
    # Written and searched only through raw SQL with an explicit ::vector cast
    # (see embeddings.to_pgvector); never loaded into Python.
    embedding: Mapped[list[float] | None] = mapped_column(Vector(EMBEDDING_DIMS), nullable=True)
    # Generated by Postgres: never written by us and never read into Python.
    # Mapped only so autogenerate doesn't try to drop it.
    search_tsv: Mapped[str | None] = mapped_column(
        TSVECTOR, Computed(SEARCH_TSV_EXPR, persisted=True), nullable=True
    )

    __table_args__ = (
        Index("portfolio_chunks_mode_idx", "mode"),
        Index("portfolio_chunks_search_idx", "search_tsv", postgresql_using="gin"),
        Index(
            "portfolio_chunks_embedding_idx",
            "embedding",
            postgresql_using="hnsw",
            postgresql_ops={"embedding": "vector_cosine_ops"},
        ),
    )
